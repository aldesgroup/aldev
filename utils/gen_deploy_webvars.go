package utils

import (
	"fmt"
	"path"
	"strings"

	core "github.com/aldesgroup/corego"
	"gopkg.in/yaml.v3"
)

// ----------------------------------------------------------------------------
// Generating API config files
// ----------------------------------------------------------------------------

func generateWebEnvVars(fileName string, envName string, envConfig yaml.Node, regen bool) {
	// getting the env type
	var envType core.EnvType
	if envName == "local" {
		envType = core.EnvTypeLOCAL
	} else {
		envType = getEnvType(envName, true)
	}

	// checking the existing config file
	envFileName := path.Join(Config().Web.Build.SrcDir, fileName)
	if core.FileExists(envFileName) && !regen {
		Debug("%s already exists!", envFileName)
		return
	}

	// computing the API URL for the current environment - and the app name
	var apiURL string
	if envType == core.EnvTypeLOCAL {
		apiURL = fmt.Sprintf("http://localhost:%d", Config().API.Runtimes.Local.Port)
	} else {
		apiURL = fmt.Sprintf("https://%s.%s/%s-%s",
			getEnvParamValue(envName, Config().Deploying.Platform.Config.Environments[envName], "apim_name"),
			GetRemoteDeploymentGenerator().getPlatformHost(),
			Config().AppNameLower,
			envName,
		)
	}
	appName := Config().AppName
	if envType != core.EnvTypePRODUCTION {
		appName += " (" + envName + ")"
	}

	// retrieving the env vars, using the common ones
	envVarsNode := mergeYAMLNodes(&Config().Web.EnvVars.Common, &envConfig)
	envVarsNode = prependValue("VITE_APP_LANGS", "en,"+Config().Languages, envVarsNode)
	envVarsNode = prependValue("VITE_API_URL", apiURL, envVarsNode)
	envVarsNode = prependValue("VITE_APP_NAME", appName, envVarsNode)

	// building the key-value pairs
	envVars := []string{}
	for i := 0; i < len(envVarsNode.Content); i += 2 {
		key := envVarsNode.Content[i]
		val := envVarsNode.Content[i+1]
		envVars = append(envVars, key.Value+"="+val.Value)
	}

	// writing the env vars to the file
	core.WriteStringToFile(envFileName, "# Generated by Aldev, do not edit!\n%s", strings.Join(envVars, "\n"))
}
