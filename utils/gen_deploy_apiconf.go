package utils

import (
	"fmt"
	"path"
	"strings"

	core "github.com/aldesgroup/corego"
	"gopkg.in/yaml.v3"
)

// ----------------------------------------------------------------------------
// Generating API config files
// ----------------------------------------------------------------------------

func generateAPIConfFile(envName string, envConfig *APIRuntimeConfig, regen bool) map[string]any {
	// checking the existing config file
	confFileName := fmt.Sprintf("%s/conf-%s.yaml", Config().API.Build.SrcDir, envName)
	if core.FileExists(confFileName) && !regen {
		Debug("%s already exists!", confFileName)
		return *core.ReadFileFromYAML(confFileName, &map[string]any{}, true)
	}

	// building the base config for the current environment
	base := mergeYAMLNodes(&Config().API.Runtimes.Common.Base, &envConfig.Base)
	base = prependValue("version", "_$_VERSION_$_", base)
	base = prependValue("port", getEnvPortString(envConfig), base)
	base = prependValue("appdesc", Config().AppDesc, base)
	base = prependValue("appname", Config().AppName, base)

	// making a new config by merging the env config on top of the common config
	newConf := &struct {
		Base   yaml.Node
		Custom yaml.Node
	}{
		Base:   *base,
		Custom: *mergeYAMLNodes(&Config().API.Runtimes.Common.Custom, &envConfig.Custom),
	}

	// marshalling
	newConfBytes, errMarsh := yaml.Marshal(newConf)
	core.PanicMsgIfErr(errMarsh, "Could not marshal merged config for env '%s'", envName)

	// writing out the file
	core.WriteStringToFile(confFileName, "# Generated by Aldev, do not edit!\n%s", string(newConfBytes))
	Debug("Just wrote file : %s", confFileName)

	// returning the resolved - i.e. merged - config as a map[string]any for further use
	var resolvedConfig map[string]any
	errUnmarsh := yaml.Unmarshal(newConfBytes, &resolvedConfig)
	core.PanicMsgIfErr(errUnmarsh, "Could not unmarshal merged config for env '%s'", envName)

	return resolvedConfig
}

// ----------------------------------------------------------------------------
// Generating / updating the .env.local file containing the secrets
// ----------------------------------------------------------------------------

const localSecretsFileName = ".env.local"

func generateLocalSecretsFile(secrets []string) {
	// path to the .env.local file containing the secrets
	localSecretsFilePath := path.Join(Config().Deploying.Dir, "local", localSecretsFileName)

	// key-value pairs
	keyValuePairs := make(map[string]string)

	// reading the existing file if it exists
	if core.FileExists(localSecretsFilePath) {
		lines := strings.Split(string(core.ReadFile(localSecretsFilePath, false)), "\n")
		for _, line := range lines {
			if parts := strings.SplitN(line, "=", 2); len(parts) == 2 {
				keyValuePairs[parts[0]] = parts[1]
			}
		}
	}

	// building the content of the .env.local file
	var contentBuilder strings.Builder
	contentBuilder.WriteString("# Generated by Aldev, do not edit the keys, only the values!\n")
	for _, secret := range secrets {
		contentBuilder.WriteString(fmt.Sprintf("%s=%s\n", secret, keyValuePairs[secret]))
	}

	// writing the content to the .env.local file
	core.WriteStringToFile(localSecretsFilePath, "%s", contentBuilder.String())
}
