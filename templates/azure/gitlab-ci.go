package azure

import core "github.com/aldesgroup/corego"

func GitlabAzureCIxCDxCONF(withWeb bool) string {
	return `# Generated by Aldev, do not edit!

stages: [build, deploy_test, deploy_prod]

# --------------------------------------------------------------------------- #
# --- This is the default behaviour of each step
#
# MAKE SURE GITLAB KNOWS THE VALUES FOR THESE VARIABLES:
# - {GITLAB_CID_SNAKE}_TENANT_ID
# - {GITLAB_CID_SNAKE}_CLIENT_ID
# in the project's or its group's CI/CD settings, for the deploy steps to work.
# --------------------------------------------------------------------------- #

default:
    id_tokens:
        AZURE_ID_TOKEN:
            aud: api://AzureADTokenExchange
    before_script:
        - VERSION=$(cat VERSION)
        - |
            az login                                   {SOME_SPACE} \
              --service-principal                      {SOME_SPACE} \
              --tenant                 ${{GITLAB_CID_SNAKE}_TENANT_ID} \
              --username               ${{GITLAB_CID_SNAKE}_CLIENT_ID} \
              --federated-token        $AZURE_ID_TOKEN {SOME_SPACE} \
              --output                 none            {SOME_SPACE} \
              --allow-no-subscriptions

# --------------------------------------------------------------------------- #
# --- Defining reusable instructions
# --------------------------------------------------------------------------- #

.azure_set_acr_sub: &azure_set_acr_sub
    - az account set --subscription {acr_sub_name}

.acr_podman_login: &acr_podman_login
    - ACR_TOKEN=$(az acr login --name {acr_name} --expose-token --query accessToken -o tsv)
    - echo $ACR_TOKEN | podman login {acr_name}.azurecr.io -u 00000000-0000-0000-0000-000000000000 --password-stdin

# Writes the deploy token to a temp file consumed by --mount=type=secret in the build.
.git_token_setup: &git_token_setup
    - echo "$GIT_DEPLOY_USER:$GIT_DEPLOY_TOKEN" > /tmp/git_token

# Rules shared by all dev pipeline jobs.
.dev_pipeline_rules: &dev_pipeline_rules
    - if: "$CI_COMMIT_MESSAGE =~ /^dev: bumped version/"
      when: never
    - if: '$CI_COMMIT_BRANCH == "main"'
      when: on_success

# Rules shared by all releases pipeline jobs (except deploy_prd which is manual).
.releases_pipeline_rules: &releases_pipeline_rules
    - if: '$CI_COMMIT_BRANCH == "releases"'
      when: on_success

# Runs terraform init + apply in the given directory (ARM_USE_CLI lets TF reuse the az login).
.apim_tf_apply: &apim_tf_apply
    - export PATH="/home/linuxbrew/.linuxbrew/bin:$PATH"
    - export ARM_USE_CLI=true
    - az account set --subscription {identity_sub_name} && terraform -chdir=$TF_DIR init
    - terraform -chdir=$TF_DIR apply -auto-approve
` +
		core.IfThenElse(withWeb, `
# Builds the web app with podman, so the runner does not need Node.
.web_build: &web_build
    - |
        podman run --rm --user 0 -v "$PWD/web:/app:z" -w /app \
          quay.io/hummingbird/nodejs:26-builder sh -c "npm ci && npm run build -- --mode $WEB_ENV --outDir dist-$WEB_ENV"
`, ``) +
		`
# --------------------------------------------------------------------------- #
# --- Building & deploying on {env-SANDBOX}, with each new commit on main
# --------------------------------------------------------------------------- #

build_{env-SANDBOX}:
    stage: build
    tags: [{resource_ns}, {env-SANDBOX}]
    script:
        - *azure_set_acr_sub
        - *acr_podman_login
        - *git_token_setup
        - sed -i "s/_\$_VERSION_\$_/${CI_COMMIT_SHORT_SHA}/g" api/conf-{env-SANDBOX}.yaml
        - export IMAGE={acr_name}.azurecr.io/{{.AppNameKebab}}-api:${CI_COMMIT_SHORT_SHA}
        - podman build -t $IMAGE -f {{.Deploying.Dir}}/Containerfile --build-arg ENV={env-SANDBOX} --secret id=git_token,src=/tmp/git_token .
        - podman push $IMAGE
    rules: *dev_pipeline_rules
` +
		core.IfThenElse(withWeb, `
build_web_{env-SANDBOX}:
    stage: build
    tags: [{resource_ns}, {env-SANDBOX}]
    variables:
        WEB_ENV: {env-SANDBOX}
    script:
        - *web_build
    artifacts:
        paths: [web/dist-{env-SANDBOX}]
        expire_in: 1 week
    rules: *dev_pipeline_rules
`, ``) +
		`
deploy_{env-SANDBOX}:
    stage: deploy_test
    tags: [{resource_ns}, {env-SANDBOX}]
    needs: [build_{env-SANDBOX}]
    script:
        - |
            az containerapp update                                         {APP_NAME_SPACE2} \
              --subscription   {sub-SANDBOX}                                {APP_NAME_SPACE2} \
              --name           aca-{resource_ns}-{env-SANDBOX}-{{.AppNameLower}}                                {APP_NAME_SPACE1} \
              --resource-group rg-{resource_ns}-{env-SANDBOX}-{{.AppNameLower}}                                 {APP_NAME_SPACE1} \
              --container-name {{.AppNameKebab}}-api                                         \
              --image          {acr_name}.azurecr.io/{{.AppNameKebab}}-api:${CI_COMMIT_SHORT_SHA} \
              --output         none
    environment:
        name: {env-SANDBOX}
    rules: *dev_pipeline_rules

apim_{env-SANDBOX}:
    stage: deploy_test
    tags: [{resource_ns}, {env-SANDBOX}]
    needs: [deploy_{env-SANDBOX}]
    variables:
        TF_DIR: {{.Deploying.Dir}}/remote/b-apim/1-{env-SANDBOX}
    script:
        - *azure_set_acr_sub
        - *apim_tf_apply
    environment:
        name: {env-SANDBOX}
    rules: *dev_pipeline_rules
` +
		core.IfThenElse(withWeb, `
deploy_web_{env-SANDBOX}:
    stage: deploy_test
    tags: [{resource_ns}, {env-SANDBOX}]
    needs: [build_web_{env-SANDBOX}]
    variables:
        WEB_ENV: {env-SANDBOX}
    script:
        - |
            az storage blob upload-batch   {APP_NAME_SPACE0} \
              --account-name st{resource_ns}{env-SANDBOX}{{.AppNameLower}}web    \
              --destination  '$web'        {APP_NAME_SPACE0} \
              --source       web/dist-{env-SANDBOX}  {APP_NAME_SPACE0} \
              --auth-mode    login         {APP_NAME_SPACE0} \
              --output       none          {APP_NAME_SPACE0} \
              --overwrite
        - |
            az afd endpoint purge             {APP_NAME_SPACE0} \
              --subscription   {fd-sub-SANDBOX}   {APP_NAME_SPACE0} \
              --resource-group {fd-rg-SANDBOX}  {APP_NAME_SPACE0} \
              --profile-name   {fd-name-SANDBOX}   {APP_NAME_SPACE0} \
              --endpoint-name  fde-{resource_ns}-{env-SANDBOX}-{{.AppNameLower}}    \
              --content-paths  '/*'           {APP_NAME_SPACE0} \
              --output         none                       \
              --no-wait
    environment:
        name: {env-SANDBOX}
    rules: *dev_pipeline_rules
`, ``) +
		`
# --------------------------------------------------------------------------- #
# --- Building on {env-STAGING} & {env-PRODUCTION}, and deploying {env-STAGING}
# --------------------------------------------------------------------------- #

build_{env-STAGING}_n_{env-PRODUCTION}:
    stage: build
    tags: [{resource_ns}, {env-STAGING}]
    script:
        - *azure_set_acr_sub
        - *acr_podman_login
        - *git_token_setup
        - sed -i "s/_\$_VERSION_\$_/$VERSION/g" api/conf-{env-STAGING}.yaml
        - export IMAGE_STAGING={acr_name}.azurecr.io/{{.AppNameKebab}}-api:$VERSION-{env-STAGING}
        - podman build -t $IMAGE_STAGING -f {{.Deploying.Dir}}/Containerfile --build-arg ENV={env-STAGING} --secret id=git_token,src=/tmp/git_token .
        - podman push $IMAGE_STAGING
        - sed -i "s/_\$_VERSION_\$_/$VERSION/g" api/conf-{env-PRODUCTION}.yaml
        - export IMAGE_PRODUCTION={acr_name}.azurecr.io/{{.AppNameKebab}}-api:$VERSION-{env-PRODUCTION}
        - podman build -t $IMAGE_PRODUCTION -f {{.Deploying.Dir}}/Containerfile --build-arg ENV={env-PRODUCTION} --secret id=git_token,src=/tmp/git_token .
        - podman push $IMAGE_PRODUCTION
    rules: *releases_pipeline_rules
` +
		core.IfThenElse(withWeb, `
build_web_{env-STAGING}_n_{env-PRODUCTION}:
    stage: build
    tags: [{resource_ns}, {env-STAGING}]
    script:
        - WEB_ENV={env-STAGING}
        - *web_build
        - WEB_ENV={env-PRODUCTION}
        - *web_build
    artifacts:
        paths: [web/dist-{env-STAGING}, web/dist-{env-PRODUCTION}]
        expire_in: 1 week
    rules: *releases_pipeline_rules
`, ``) +
		`
deploy_{env-STAGING}:
    stage: deploy_test
    tags: [{resource_ns}, {env-STAGING}]
    needs: [build_{env-STAGING}_n_{env-PRODUCTION}]
    script:
        - |
            az containerapp update                               {APP_NAME_SPACE2} \
              --subscription   {sub-STAGING}                      {APP_NAME_SPACE2} \
              --name           aca-{resource_ns}-{env-STAGING}-{{.AppNameLower}}                      {APP_NAME_SPACE1} \
              --resource-group rg-{resource_ns}-{env-STAGING}-{{.AppNameLower}}                       {APP_NAME_SPACE1} \
              --container-name {{.AppNameKebab}}-api                               \
              --image          {acr_name}.azurecr.io/{{.AppNameKebab}}-api:$VERSION-{env-STAGING} \
              --output         none
    environment:
        name: {env-STAGING}
    rules: *releases_pipeline_rules

apim_{env-STAGING}:
    stage: deploy_test
    tags: [{resource_ns}, {env-STAGING}]
    needs: [deploy_{env-STAGING}]
    variables:
        TF_DIR: {{.Deploying.Dir}}/remote/b-apim/2-{env-STAGING}
    script:
        - *azure_set_acr_sub
        - *apim_tf_apply
    environment:
        name: {env-STAGING}
    rules: *releases_pipeline_rules
` +
		core.IfThenElse(withWeb, `
deploy_web_{env-STAGING}:
    stage: deploy_test
    tags: [{resource_ns}, {env-STAGING}]
    needs: [build_web_{env-STAGING}_n_{env-PRODUCTION}]
    variables:
        WEB_ENV: {env-STAGING}
    script:
        - |
            az storage blob upload-batch   {APP_NAME_SPACE0} \
              --account-name st{resource_ns}{env-STAGING}{{.AppNameLower}}web    \
              --destination  '$web'        {APP_NAME_SPACE0} \
              --source       web/dist-{env-STAGING}  {APP_NAME_SPACE0} \
              --auth-mode    login         {APP_NAME_SPACE0} \
              --output       none          {APP_NAME_SPACE0} \
              --overwrite
        - |
            az afd endpoint purge             {APP_NAME_SPACE0} \
              --subscription   {fd-sub-STAGING}   {APP_NAME_SPACE0} \
              --resource-group {fd-rg-STAGING}  {APP_NAME_SPACE0} \
              --profile-name   {fd-name-STAGING}   {APP_NAME_SPACE0} \
              --endpoint-name  fde-{resource_ns}-{env-STAGING}-{{.AppNameLower}}    \
              --content-paths  '/*'           {APP_NAME_SPACE0} \
              --output         none                       \
              --no-wait
    environment:
        name: {env-STAGING}
    rules: *releases_pipeline_rules
`, ``) +
		`
# --------------------------------------------------------------------------- #
# --- Deploying {env-PRODUCTION}
# --------------------------------------------------------------------------- #

deploy_{env-PRODUCTION}:
    stage: deploy_prod
    tags: [{resource_ns}, {env-PRODUCTION}]
    needs: [deploy_{env-STAGING}]
    script:
        - |
            az containerapp update                               {APP_NAME_SPACE2} \
              --subscription   {sub-PRODUCTION}                      {APP_NAME_SPACE2} \
              --name           aca-{resource_ns}-{env-PRODUCTION}-{{.AppNameLower}}                      {APP_NAME_SPACE1} \
              --resource-group rg-{resource_ns}-{env-PRODUCTION}-{{.AppNameLower}}                       {APP_NAME_SPACE1} \
              --container-name {{.AppNameKebab}}-api                               \
              --image          {acr_name}.azurecr.io/{{.AppNameKebab}}-api:$VERSION-{env-PRODUCTION} \
              --output         none
    environment:
        name: {env-PRODUCTION}
    rules:
        - if: '$CI_COMMIT_BRANCH == "releases"'
          when: manual

apim_{env-PRODUCTION}:
    stage: deploy_prod
    tags: [{resource_ns}, {env-PRODUCTION}]
    needs: [deploy_{env-PRODUCTION}]
    variables:
        TF_DIR: {{.Deploying.Dir}}/remote/b-apim/3-{env-PRODUCTION}
    script:
        - *azure_set_acr_sub
        - *apim_tf_apply
    environment:
        name: {env-PRODUCTION}
    rules: *releases_pipeline_rules
` +
		core.IfThenElse(withWeb, `
deploy_web_{env-PRODUCTION}:
    stage: deploy_prod
    tags: [{resource_ns}, {env-PRODUCTION}]
    needs: [deploy_web_{env-STAGING}, build_web_{env-STAGING}_n_{env-PRODUCTION}]
    variables:
        WEB_ENV: {env-PRODUCTION}
    script:
        - |
            az storage blob upload-batch   {APP_NAME_SPACE0} \
              --account-name st{resource_ns}{env-PRODUCTION}{{.AppNameLower}}web    \
              --destination  '$web'        {APP_NAME_SPACE0} \
              --source       web/dist-{env-PRODUCTION}  {APP_NAME_SPACE0} \
              --auth-mode    login         {APP_NAME_SPACE0} \
              --output       none          {APP_NAME_SPACE0} \
              --overwrite
        - |
            az afd endpoint purge             {APP_NAME_SPACE0} \
              --subscription   {fd-sub-PRODUCTION}   {APP_NAME_SPACE0} \
              --resource-group {fd-rg-PRODUCTION}  {APP_NAME_SPACE0} \
              --profile-name   {fd-name-PRODUCTION}   {APP_NAME_SPACE0} \
              --endpoint-name  fde-{resource_ns}-{env-PRODUCTION}-{{.AppNameLower}}    \
              --content-paths  '/*'           {APP_NAME_SPACE0} \
              --output         none                       \
              --no-wait
    environment:
        name: {env-PRODUCTION}
    rules:
        - if: '$CI_COMMIT_BRANCH == "releases"'
          when: manual
`, ``)
}
